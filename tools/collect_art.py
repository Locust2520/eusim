#!/usr/bin/env python3
"""Pick the best generated images from /opt/ordinatrice/imggen and copy them into assets/art/.
Re-run whenever new images are generated."""
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = '/opt/ordinatrice/imggen'
EXPRS = ['neutral', 'happy', 'angry', 'surprised', 'worried']
# Old batch (some portraits had spurious glasses). Only keep those where glasses are correct
# or absent in reality and in the image.
OLD_OK = {'schulz', 'timmermans', 'meloni', 'verhofstadt', 'selmayr', 'schuman', 'delors',
          'schauble', 'costa', 'borrell', 'juncker', 'merz', 'monnet'}


def _unused_pick(k, e):
    c = [f'{GEN}/out/pt_{k}_{e}.png']
    if k in OLD_OK:
        c.append(f'{GEN}/old/p_{k}_{e}.png')
    for p in c:
        if os.path.exists(p):
            return p
    return None


def main():
    dst = os.path.join(ROOT, 'assets/art/portraits')
    os.makedirs(dst, exist_ok=True)
    keys = set()
    for f in os.listdir(f'{GEN}/src'):
        keys.add(f.split('.')[0])
    n = 0
    for k in sorted(keys):
        new = {e: f'{GEN}/out/pt_{k}_{e}.png' for e in EXPRS if os.path.exists(f'{GEN}/out/pt_{k}_{e}.png')}
        old = {e: f'{GEN}/old/p_{k}_{e}.png' for e in EXPRS if os.path.exists(f'{GEN}/old/p_{k}_{e}.png')} if k in OLD_OK else {}
        if 'neutral' not in new:
            new = {}
        if 'neutral' not in old:
            old = {}
        chosen = new if len(new) >= len(old) else old
        for e, p in chosen.items():
            out = os.path.join(dst, f'{k}_{e}.png')
            if not os.path.exists(out) or os.path.getmtime(p) > os.path.getmtime(out) or os.path.getsize(p) != os.path.getsize(out):
                shutil.copy(p, out)
                n += 1
        for e in EXPRS:  # drop stale expressions from another batch
            out = os.path.join(dst, f'{k}_{e}.png')
            if e not in chosen and os.path.exists(out):
                os.remove(out)
    # fictional characters & misc art generated by name
    for f in os.listdir(f'{GEN}/out'):
        for prefix, sub in (('fx_', 'fictional'), ('cr_', 'creatures'), ('ui_', 'ui'), ('bg_', 'backgrounds'),
                            ('bd_', 'buildings'), ('ow_', 'overworld'), ('it_', 'items')):
            if f.startswith(prefix):
                d = os.path.join(ROOT, 'assets/art', sub)
                os.makedirs(d, exist_ok=True)
                out = os.path.join(d, f[len(prefix):])
                src = f'{GEN}/out/{f}'
                if not os.path.exists(out) or os.path.getmtime(src) > os.path.getmtime(out):
                    shutil.copy(src, out)
                    n += 1
    print('collected', n)


if __name__ == '__main__':
    main()
