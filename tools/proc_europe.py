#!/usr/bin/env python3
"""Europe map for the bottom screen (Natural Earth 1:110m, public domain) + city marker coordinates."""
import json, os
from PIL import Image, ImageDraw
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EU = {'Austria', 'Belgium', 'Bulgaria', 'Croatia', 'Cyprus', 'Czechia', 'Denmark', 'Estonia', 'Finland', 'France',
      'Germany', 'Greece', 'Hungary', 'Ireland', 'Italy', 'Latvia', 'Lithuania', 'Luxembourg', 'Malta', 'Netherlands',
      'Poland', 'Portugal', 'Romania', 'Slovakia', 'Slovenia', 'Spain', 'Sweden', 'Czech Republic'}
CITIES = [  # key, label, lon, lat
    ('bruxelles', "Brussels", 4.35, 50.85), ('luxembourg', 'Luxembourg', 6.13, 49.61),
    ('francfort', "Frankfurt", 8.68, 50.11), ('strasbourg', 'Strasbourg', 7.75, 48.58),
    ('paris', 'Paris', 2.35, 48.86), ('londres', "London", -0.13, 51.51), ('athenes', "Athens", 23.73, 37.98),
    ('budapest', 'Budapest', 19.04, 47.5), ('anvers', "Antwerp", 4.40, 51.22), ('varsovie', "Warsaw", 21.0, 52.23),
    ('rome', 'Rome', 12.5, 41.9), ('lisbonne', "Lisbon", -9.14, 38.72), ('maastricht', 'Maastricht', 5.69, 50.85),
]


def proj(lon, lat):
    return (lon + 11) * 5.6, (61 - lat) * 7.6


def main():
    out = os.path.join(ROOT, 'nitrofs/ui/europe.bgi')
    hdr = os.path.join(ROOT, 'include/gen/europe.h')
    if os.path.exists(out) and os.path.getmtime(out) > os.path.getmtime(__file__):
        return
    import mkgfx
    gj = json.load(open(os.path.join(ROOT, 'assets/geo/ne110.geojson')))
    im = Image.new('RGB', (256, 192), (56, 112, 200))
    d = ImageDraw.Draw(im)
    for y in range(0, 192, 4):
        d.line([(0, y), (256, y)], fill=(64, 122, 210))
    for f in gj['features']:
        name = f['properties'].get('NAME') or f['properties'].get('ADMIN')
        g = f['geometry']
        polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
        eu = name in EU or f['properties'].get('ADMIN') in EU
        fill = (120, 196, 104) if eu else (200, 196, 172)
        edge = (60, 120, 56) if eu else (140, 136, 120)
        for poly in polys:
            pts = [proj(x, y) for x, y in poly[0]]
            if all(px < -50 or px > 300 or py < -50 or py > 260 for px, py in pts):
                continue
            d.polygon(pts, fill=fill, outline=edge)
    idx, pal = mkgfx.quantize_rgb(im, 24)
    mkgfx.write_bg(out, idx, pal, 1)
    im.resize((512, 384), Image.NEAREST).save('/tmp/europe.png')
    lines = ['// Generated by tools/proc_europe.py', '#pragma once',
             'typedef struct { const char *key, *label; short x, y; } EuropeCity;',
             f'#define NUM_EUROPE_CITIES {len(CITIES)}',
             'static const EuropeCity europe_cities[] = {']
    for k, l, lon, lat in CITIES:
        x, y = proj(lon, lat)
        lines.append(f'  {{"{k}", "{l}", {int(x)}, {int(y)}}},')
    lines.append('};')
    open(hdr, 'w').write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    import sys
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    main()
