#!/usr/bin/env python3
"""data/*.json -> source/gen/data.c, include/gen/data_ids.h, build/*_ids.json"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'data') if os.path.exists(os.path.join(ROOT, 'data/species.json')) else os.path.join(ROOT, 'data_stub')
EFFECTS = ['NONE', 'LOBBY', 'SCANDALE', 'GEL', 'SOMMEIL', 'BLOQUE', 'CONFUSE', 'FLINCH', 'STAT_UP', 'STAT_DOWN',
           'HEAL_HALF', 'DRAIN', 'RECOIL', 'MULTI_HIT', 'HIGH_CRIT', 'FIXED_LEVEL', 'PROTECT', 'PAY_DAY', 'REST',
           'CHARGE', 'HAZE', 'LEAVE', 'COPY', 'ERASE', 'ALWAYS_HIT', 'STEAL_TURN', 'SELF_DESTRUCT', 'TRAP']
CATS = {'phys': 0, 'spec': 1, 'status': 2}
GROW = {'fast': 0, 'medium': 1, 'slow': 2, 'parabolic': 3}
KINDS = ['ball', 'heal', 'status', 'revive', 'pp', 'battle', 'evo', 'key', 'repel', 'misc']


def load(name, default=None):
    p = os.path.join(D, name)
    if not os.path.exists(p):
        return default
    return json.load(open(p, encoding='utf-8'))


def cstr(s):
    if s is None:
        return 'NULL'
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'


def main():
    types = load('types.json')
    moves = load('moves.json', [])
    species = sorted(load('species.json', []), key=lambda s: s['num'])
    items = load('items.json', [])
    trainers = load('trainers.json', [])
    encs = load('encounters.json', {})
    if not types:
        return
    tidx = {t: i for i, t in enumerate(types['types'])}
    midx = {m['id']: i for i, m in enumerate(moves)}
    sidx = {s['id']: i for i, s in enumerate(species)}
    iidx = {it['id']: i for i, it in enumerate(items)}
    tridx = {t['id']: i for i, t in enumerate(trainers)}
    eidx = {k: i for i, k in enumerate(encs)}
    os.makedirs(os.path.join(ROOT, 'build'), exist_ok=True)
    for name, tab in (('species', sidx), ('item', iidx), ('move', midx), ('trainer', tridx), ('enc', eidx)):
        json.dump(tab, open(os.path.join(ROOT, f'build/{name}_ids.json'), 'w'), indent=0)

    out = ['// Generated by tools/mkdata.py — do not edit', '#include "data.h"', '']
    out.append('const char *type_names[NUM_TYPES] = {' + ','.join(cstr(n) for n in types['names']) + '};')
    chart = [[2] * 16 for _ in range(16)]
    for a, row in types['chart'].items():
        for d, v in row.items():
            chart[tidx[a]][tidx[d]] = {0: 0, 0.0: 0, 0.5: 1, 1: 2, 1.0: 2, 2: 4, 2.0: 4}[v]
    out.append('const u8 type_chart[NUM_TYPES][NUM_TYPES] = {')
    for r in chart:
        out.append('  {' + ','.join(map(str, r)) + '},')
    out.append('};')
    out.append('MoveData moves[] = {')
    for m in moves:
        out.append('  {%s, %d, %d, %d, %d, %d, EF_%s, %d, %d, %d, %s},' % (
            cstr(m['name']), tidx[m['type']], CATS[m['cat']], m['power'], m['acc'], m['pp'],
            m['effect'], m.get('chance', 0), m.get('param', 0), m.get('priority', 0), cstr(m['desc'])))
    out.append('};')
    out.append(f'const int NUM_MOVES = {len(moves)};')
    for s in species:
        flat = []
        for lv, mv in s['moves']:
            flat += [lv, midx[mv]]
        out.append(f'static const u16 learn_{s["id"]}[] = {{' + ','.join(map(str, flat + [0xFFFF])) + '};')
    out.append('SpeciesData species[] = {')
    for s in species:
        t1 = tidx[s['types'][0]]
        t2 = tidx[s['types'][1]] if len(s['types']) > 1 else t1
        evo = s.get('evo') or {}
        into = sidx[evo['into']] if evo.get('into') else 0xFFFF
        lvl = evo.get('level', 0) or 0
        eitem = iidx[evo['item']] if evo.get('item') else 0xFFFF
        out.append('  {%s, %d, %d, %d, {%s}, %d, %d, %d, %d, %d, %d, learn_%s, %s, %s},' % (
            cstr(s['name']), s['num'], t1, t2, ','.join(map(str, s['base'])), GROW[s['growth']], s['catch'],
            s['exp'], into, lvl, eitem, s['id'], cstr(s['dex']), cstr(s.get('category', ''))))
    out.append('};')
    out.append(f'const int NUM_SPECIES = {len(species)};')
    out.append('ItemData items[] = {')
    for it in items:
        out.append('  {%s, %d, %d, %d, %s},' % (cstr(it['name']), KINDS.index(it['kind']), it.get('price', 0),
                                                it.get('param', 0), cstr(it['desc'])))
    out.append('};')
    out.append(f'const int NUM_ITEMS_DEF = {len(items)};')
    sprite_ids = json.load(open(os.path.join(ROOT, 'build/sprite_ids.json')))
    for t in trainers:
        flat = []
        for sp, lv in t['party']:
            flat += [sidx[sp], lv]
        out.append(f'static const u16 party_{t["id"]}[] = {{' + ','.join(map(str, flat)) + '};')
    out.append('TrainerData trainers[] = {' if trainers else 'TrainerData trainers[1] = {{0}};')
    for t in trainers:
        out.append('  {%s, %s, %s, %d, %d, %d, %d, party_%s, %s, %s, %s, %s},' % (
            cstr(t['name']), cstr(t.get('cls', '')), cstr(t.get('portrait')), sprite_ids[t.get('sprite', 'fonctionnaire')],
            t.get('money', 100), t.get('ai', 1), len(t['party']), t['id'], cstr(t.get('intro', '')),
            cstr(t.get('defeat', '')), cstr(t.get('win', '')), cstr(t.get('music'))))
    if trainers:
        out.append('};')
    out.append(f'const int NUM_TRAINERS = {len(trainers)};')
    for k, e in encs.items():
        out.append(f'static const EncSlot enc_{k}[] = {{' + ','.join(
            '{%d,%d,%d,%d}' % (sidx[s[0]], s[1], s[2], s[3]) for s in e['slots']) + '};')
    out.append('const EncTable enc_tables[] = {' if encs else 'const EncTable enc_tables[1] = {{0}};')
    for k, e in encs.items():
        out.append('  {%d, %d, enc_%s},' % (e['rate'], len(e['slots']), k))
    if encs:
        out.append('};')
    out.append(f'const int NUM_ENC = {len(encs)};')
    os.makedirs(os.path.join(ROOT, 'source/gen'), exist_ok=True)
    open(os.path.join(ROOT, 'source/gen/data.c'), 'w').write('\n'.join(out) + '\n')

    h = ['// Generated by tools/mkdata.py', '#pragma once']
    for pre, tab in (('SP', sidx), ('IT', iidx), ('MV', midx), ('TR', tridx), ('ENC', eidx)):
        for k, v in tab.items():
            h.append(f'#define {pre}_{k.upper()} {v}')
    for k, v in tidx.items():
        h.append(f'#define TYPE_{k} {v}')
    open(os.path.join(ROOT, 'include/gen/data_ids.h'), 'w').write('\n'.join(h) + '\n')
    print('data: species', len(species), 'moves', len(moves), 'items', len(items), 'trainers', len(trainers))


if __name__ == '__main__':
    main()
