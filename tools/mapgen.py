# ---------------------------------------------------------------- interiors (templates)
def interior_box(m, w, h, floor='o'):
    """Walls on the top 2 rows, floor elsewhere, doormat bottom centre. Returns doormat x."""
    m.rect(LEGEND[floor] if floor in LEGEND else floor, 0, 0, w, h)
    m.rect('wall_top', 0, 0, w, 1)
    m.rect('wall', 0, 1, w, 1)
    for x in range(2, w - 2, 4):
        m.rect('window', x, 1)
    dx = w // 2
    m.rect('doormat', dx, h - 1)
    return dx


def link(outdoor, door_x, door_y, inner, in_x, in_y):
    outdoor.ev(f'door {door_x} {door_y} {inner.id} {in_x} {in_y - 1} up')
    inner.ev(f'warp {in_x} {in_y} {outdoor.id} {door_x} {door_y + 1} down')


