#!/usr/bin/env python3
"""Generates assets/maps/*.map for the whole world of EU Simulator from compact Python specs.

Each outdoor map is painted with a small API (rects of ground tiles, objects, roads), buildings get
their interiors generated and wired automatically (doors <-> doormats).
"""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'assets/maps')

LEGEND = {
    '.': 'grass', ',': 'grass1', ';': 'grass2', '*': 'flowers_r', '+': 'flowers_y', '%': 'flowers_p',
    '"': 'dossiers', '=': 'pave', '-': 'road', 'h': 'road_h', 'v': 'road_v', 'z': 'zebra', '~': 'water',
    ':': 'path', 's': 'sand', 'L': 'ledge', 'H': 'hedge', 'F': 'fence', 'r': 'rock', 'w': 'snow',
    'W': 'snow_enc', 'k': 'dock', 'g': 'green', 'G': 'golf', 'm': 'marble', 'C': 'red_carpet', 't': 'tracks',
    'q': 'tiles', 'o': 'floor', 'c': 'carpet', 'e': 'carpet_enc', 'd': 'dark', 'D': 'dark_enc',
    '#': 'wall_top', '|': 'wall', 'n': 'window', '_': 'doormat', 'b': 'bench_row', 'R': 'carpet_red',
    '^': 'stairs', 'x': 'counter', 'X': 'void', 'p': 'chair', '@': 'seat', '$': 'money', '&': 'cobweb',
}


class M:
    def __init__(self, mid, name, w, h, fill='grass', music='', flags='outdoor', enc='none', city=None, bg=None):
        self.id, self.name, self.w, self.h = mid, name, w, h
        self.fill, self.music, self.flags, self.enc, self.city, self.bg = fill, music, flags, enc, city, bg
        inv = {v: k for k, v in LEGEND.items()}
        self.inv = inv
        self.grid = [[inv.get(fill, '.')] * w for _ in range(h)]
        self.objects = []
        self.events = []
        self.occupied = set()

    def rect(self, tile, x, y, w=1, h=1):
        ch = self.inv[tile] if len(tile) > 1 or tile not in LEGEND else tile
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                if 0 <= xx < self.w and 0 <= yy < self.h:
                    self.grid[yy][xx] = ch
        return self

    def rows(self, x, y, rows):
        for j, r in enumerate(rows):
            for i, ch in enumerate(r):
                if ch != ' ' and 0 <= x + i < self.w and 0 <= y + j < self.h:
                    self.grid[y + j][x + i] = ch
        return self

    def obj(self, name, x, y):
        self.objects.append(f'{name} {x} {y}')
        return self

    def fill_obj(self, name, x, y, w, h):
        self.objects.append(f'fill {name} {x} {y} {w} {h}')
        return self

    def border_trees(self, gaps=(), kind='tree'):
        """Trees around the edge (2 cells thick), leaving gaps: list of (side, start, length)."""
        W, H = self.w, self.h
        def gap(side, a):
            return any(s == side and st <= a < st + ln for s, st, ln in gaps)
        for x in range(0, W, 2):
            if not gap('n', x) and not gap('n', x + 1):
                self.obj(kind, x, 0)
            if not gap('s', x) and not gap('s', x + 1):
                self.obj(kind, x, H - 2)
        for y in range(2, H - 2, 2):
            if not gap('w', y) and not gap('w', y + 1):
                self.obj(kind, 0, y)
            if not gap('e', y) and not gap('e', y + 1):
                self.obj(kind, W - 2, y)
        return self

    def ev(self, line):
        self.events.append(line)
        return self

    def npc(self, name, sprite, x, y, d='down', move='still', script='-', **kw):
        extra = ' '.join(f'{k}={v}' for k, v in kw.items())
        self.events.append(f'npc {name} {sprite} {x} {y} {d} {move} {script} {extra}'.strip())
        return self

    def write(self):
        L = ['# Generated by tools/mapgen.py — edit the generator, not this file',
             f'name {self.name}', f'size {self.w} {self.h}', f'fill {self.fill}', f'flags {self.flags}',
             f'encounters {self.enc}']
        if self.music:
            L.append(f'music {self.music}')
        if self.city:
            L.append(f'city {self.city}')
        if self.bg:
            L.append(f'bg {self.bg}')
        L.append('legend')
        for k, v in LEGEND.items():
            L.append(f'  {k} {v}')
        L.append('ground')
        for r in self.grid:
            L.append('  ' + ''.join(r))
        L.append('objects')
        L += ['  ' + o for o in self.objects]
        L.append('events')
        L += ['  ' + e for e in self.events]
        open(os.path.join(OUT, self.id + '.map'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')


MAPS = []


def add(m):
    MAPS.append(m)
