#!/usr/bin/env python3
"""Extract Mona color emoji onto their native 12px grid for the DS UI."""
from pathlib import Path

from fontTools.pens.pointInsidePen import PointInsidePen
from fontTools.ttLib import TTFont
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'assets/oss/mona/Mona12ColorEmoji.woff2'
# Keep the ordering identical to the ui_icon() mapping.
ICONS = [('team', (0x1F465,)), ('bag', (0x1F392,)), ('report', (0x1F5D2,)),
         ('options', (0x2699,)), ('run_girl', (0x1F3C3, 0x200D, 0x2640, 0x200D, 0x27A1)),
         ('run_boy', (0x1F3C3, 0x200D, 0x27A1))]


def rasterize(font, codepoints):
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    names = [cmap[cp] for cp in codepoints]
    glyph = names[0]
    if len(names) > 1:
        matches = [lig.LigGlyph for lookup in font['GSUB'].table.LookupList.Lookup
                   for sub in lookup.SubTable
                   for lig in getattr(sub, 'ligatures', {}).get(glyph, [])
                   if lig.Component == names[1:]]
        if len(set(matches)) != 1:
            raise ValueError(f'Cannot resolve Mona sequence {codepoints}')
        glyph = matches[0]
    layers = font['COLR'].ColorLayers[glyph]
    colors = font['CPAL'].palettes[0]
    image = Image.new('RGBA', (12, 12))
    # Mona's pixel grid is 100 font units. Top = 1000, baseline = 0.
    # Sampling cell centres preserves the original pixel art without antialiasing.
    for layer in layers:
        color = colors[layer.colorID]
        for y in range(12):
            for x in range(12):
                pen = PointInsidePen(glyphs, (x * 100 + 50, 1000 - y * 100 - 50))
                glyphs[layer.name].draw(pen)
                if pen.getResult():
                    image.putpixel((x, y), (color.red, color.green, color.blue, color.alpha))
    return image


def main():
    with TTFont(SOURCE) as font:
        images = [rasterize(font, cp) for _, cp in ICONS]
    rgba = [[image.getpixel((x, y)) for y in range(12) for x in range(12)] for image in images]
    colors = sorted({pixel[:3] for pixels in rgba for pixel in pixels if pixel[3]})
    if len(colors) > 32:
        raise ValueError('Mona icons exceed the shared dynamic UI palette')
    lookup = {color: i + 1 for i, color in enumerate(colors)}
    palette = [(r >> 3) | ((g >> 3) << 5) | ((b >> 3) << 10) for r, g, b in colors]
    lines = [
        '// Generated by tools/mkmona.py. Mona © 2025 Monad ABXY (OFL-1.1).',
        '// Source and licence: assets/oss/mona/.',
        '#pragma once',
        f'#define MONA_ICON_COLORS {len(colors)}',
        'static const u16 mona_icon_palette[] = {' + ','.join(map(str, palette)) + '};',
        f'static const u8 mona_icon_pixels[{len(ICONS)}][144] = {{',
    ]
    for (name, _), data in zip(ICONS, rgba):
        pixels = [lookup[p[:3]] if p[3] else 0 for p in data]
        lines.append('    {' + ','.join(map(str, pixels)) + '}, // ' + name)
    lines.append('};')
    destination = ROOT / 'include/gen/mona_icons.h'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text('\n'.join(lines) + '\n')
    preview = Image.new('RGBA', (12 * len(images), 12))
    for i, image in enumerate(images):
        preview.paste(image, (i * 12, 0))
    (ROOT / 'out').mkdir(exist_ok=True)
    preview.resize((144 * len(images), 144), Image.Resampling.NEAREST).save(ROOT / 'out/mona_icons.png')
    print('Mona icons', len(images), 'colors', len(colors))


if __name__ == '__main__':
    main()
